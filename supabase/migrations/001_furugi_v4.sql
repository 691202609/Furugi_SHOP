-- ---------- atomic order creation ----------
create or replace function public.create_store_order(
  p_customer_id uuid,
  p_customer jsonb,
  p_items jsonb,
  p_payment_method text,
  p_note text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  s public.store_settings%rowtype;
  item jsonb;
  pr public.products%rowtype;
  qty integer;
  pid bigint;
  v_subtotal integer := 0;
  v_shipping integer := 0;
  v_total integer := 0;
  v_order_id text;
  v_payment_status text;
  v_name text;
  v_phone text;
  v_email text;
  v_address text;
  v_subdistrict text;
  v_district text;
  v_province text;
  v_postcode text;
begin
  select * into s from public.store_settings where id=1;
  if not found then raise exception 'STORE_SETTINGS_MISSING'; end if;

  if p_payment_method='cod' and not s.enable_cod then raise exception 'PAYMENT_DISABLED'; end if;
  if p_payment_method='promptpay' and not s.enable_promptpay then raise exception 'PAYMENT_DISABLED'; end if;
  if p_payment_method='bank' and not s.enable_bank then raise exception 'PAYMENT_DISABLED'; end if;
  if p_payment_method not in ('cod','promptpay','bank') then raise exception 'INVALID_PAYMENT'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items)=0 then raise exception 'EMPTY_CART'; end if;

  v_name := trim(coalesce(p_customer->>'name',''));
  v_phone := trim(coalesce(p_customer->>'phone',''));
  v_email := trim(coalesce(p_customer->>'email',''));
  v_address := trim(coalesce(p_customer->>'address',''));
  v_subdistrict := trim(coalesce(p_customer->>'subdistrict',''));
  v_district := trim(coalesce(p_customer->>'district',''));
  v_province := trim(coalesce(p_customer->>'province',''));
  v_postcode := trim(coalesce(p_customer->>'postcode',''));
  if v_name='' or v_phone='' or v_address='' or v_province='' then raise exception 'CUSTOMER_REQUIRED'; end if;

  -- Lock and decrement every product inside this single DB transaction.
  for item in select * from jsonb_array_elements(p_items)
  loop
    pid := nullif(item->>'id','')::bigint;
    qty := greatest(1,least(9999,coalesce(nullif(item->>'quantity','')::integer,1)));
    select * into pr from public.products where id=pid and hidden=false for update;
    if not found then raise exception 'PRODUCT_NOT_FOUND:%', pid; end if;
    if pr.sold or pr.stock < qty then raise exception 'OUT_OF_STOCK:%', pr.name; end if;
    v_subtotal := v_subtotal + (pr.price * qty);
    update public.products
      set stock = stock - qty,
          sold = (stock - qty <= 0),
          updated_at = now()
      where id = pr.id;
  end loop;

  v_shipping := case when s.free_shipping_at > 0 and v_subtotal >= s.free_shipping_at then 0 else s.shipping_fee end;
  v_total := v_subtotal + v_shipping;
  v_payment_status := case when p_payment_method='cod' then 'cod' else 'unpaid' end;
  v_order_id := 'FG' || to_char(now(),'YYMMDD') || '-' || upper(encode(gen_random_bytes(3),'hex'));

  insert into public.orders(
    id,customer_id,status,payment_method,payment_status,
    customer_name,customer_phone,customer_email,address_line,subdistrict,district,province,postcode,
    customer_note,subtotal,shipping,total
  ) values (
    v_order_id,p_customer_id,'pending',p_payment_method,v_payment_status,
    v_name,v_phone,v_email,v_address,v_subdistrict,v_district,v_province,v_postcode,
    left(coalesce(p_note,''),2000),v_subtotal,v_shipping,v_total
  );

  for item in select * from jsonb_array_elements(p_items)
  loop
    pid := nullif(item->>'id','')::bigint;
    qty := greatest(1,least(9999,coalesce(nullif(item->>'quantity','')::integer,1)));
    select * into pr from public.products where id=pid;
    insert into public.order_items(order_id,product_id,sku,name,price,quantity,size,image)
    values(v_order_id,pr.id,pr.sku,pr.name,pr.price,qty,pr.size,pr.image);
  end loop;

  return jsonb_build_object('id',v_order_id,'subtotal',v_subtotal,'shipping',v_shipping,'total',v_total,'paymentMethod',p_payment_method,'paymentStatus',v_payment_status,'status','pending');
end;
$$;

create or replace function public.cancel_store_order(p_order_id text, p_admin_note text default '')
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  o public.orders%rowtype;
  oi record;
begin
  select * into o from public.orders where id=p_order_id for update;
  if not found then return false; end if;
  if o.status='cancelled' then return true; end if;
  if not o.restocked then
    for oi in select product_id,quantity from public.order_items where order_id=p_order_id and product_id is not null
    loop
      update public.products
         set stock=least(9999,stock+oi.quantity), sold=false, updated_at=now()
       where id=oi.product_id;
    end loop;
  end if;
  update public.orders
     set status='cancelled', restocked=true,
         admin_note=case when coalesce(p_admin_note,'')='' then admin_note else left(p_admin_note,2000) end,
         updated_at=now()
   where id=p_order_id;
  return true;
end;
$$;

create or replace function public.expire_unpaid_orders()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  s public.store_settings%rowtype;
  r record;
  n integer := 0;
begin
  select * into s from public.store_settings where id=1;
  for r in
    select id from public.orders
     where status='pending' and payment_status='unpaid'
       and payment_method in ('promptpay','bank')
       and restocked=false
       and created_at < now() - make_interval(mins => greatest(30,s.reserve_minutes))
  loop
    perform public.cancel_store_order(r.id,'ยกเลิกอัตโนมัติ: ไม่พบการชำระภายในเวลาที่กำหนด');
    n := n + 1;
  end loop;
  return n;
end;
$$;

